// Command gengrammar turns a tree-sitter parser.c into a Go package for
// gositter: tables.go, lex.go and language.go. It reads the C text itself;
// no C compiler is involved.
//
//	gengrammar -lock grammars/grammars.lock -out grammars [name ...]
//
// grammars.lock lists one grammar per line:
//
//	<package> <module> <version> <dir of parser.c in the module> <sha256 of parser.c>
//
// Sources come from the Go module cache. A parser.c whose hash differs from
// the lock is refused unless -update is given, which rewrites the lock.
package main

import (
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
	"sync"
)

type lockEntry struct {
	pkg, module, version, dir, sum string
}

func (l lockEntry) parserC(modcache string) string {
	return filepath.Join(modcache, l.module+"@"+l.version, l.dir, "parser.c")
}

func main() {
	lockPath := flag.String("lock", "grammars/grammars.lock", "lock file")
	out := flag.String("out", "grammars", "output directory, one package per grammar")
	modcache := flag.String("modcache", "", "Go module cache (default: go env GOMODCACHE)")
	update := flag.Bool("update", false, "rewrite the sha256 column of the lock file")
	jobs := flag.Int("j", 4, "grammars generated at once (verilog needs about 1 GB)")
	flag.Parse()

	if *modcache == "" {
		b, err := exec.Command("go", "env", "GOMODCACHE").Output()
		if err != nil {
			die(err)
		}
		*modcache = strings.TrimSpace(string(b))
	}
	lockText, err := os.ReadFile(*lockPath)
	if err != nil {
		die(err)
	}
	var lock []lockEntry
	lines := strings.Split(string(lockText), "\n")
	lineOf := map[string]int{}
	for i, line := range lines {
		f := strings.Fields(line)
		if len(f) == 0 || strings.HasPrefix(f[0], "#") {
			continue
		}
		if len(f) < 4 || len(f) > 5 {
			die(fmt.Errorf("%s:%d: want 4 or 5 fields", *lockPath, i+1))
		}
		f = append(f, "")
		lock = append(lock, lockEntry{f[0], f[1], f[2], f[3], f[4]})
		lineOf[f[0]] = i
	}
	for _, name := range flag.Args() {
		if _, ok := lineOf[name]; !ok {
			die(fmt.Errorf("%s is not in %s", name, *lockPath))
		}
	}

	var (
		wg     sync.WaitGroup
		mu     sync.Mutex
		sem    = make(chan struct{}, *jobs)
		failed bool
	)
	for _, l := range lock {
		if flag.NArg() > 0 && !slices.Contains(flag.Args(), l.pkg) {
			continue
		}
		wg.Add(1)
		go func() {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			sum, err := generate(l, *modcache, *out, *update)
			mu.Lock()
			defer mu.Unlock()
			if err != nil {
				fmt.Fprintf(os.Stderr, "gengrammar: %s: %v\n", l.pkg, err)
				failed = true
				return
			}
			lines[lineOf[l.pkg]] = strings.Join([]string{l.pkg, l.module, l.version, l.dir, sum}, " ")
		}()
	}
	wg.Wait()
	if failed {
		os.Exit(1)
	}
	if *update {
		if err := os.WriteFile(*lockPath, []byte(strings.Join(lines, "\n")), 0o644); err != nil {
			die(err)
		}
	}
}

func die(err error) {
	fmt.Fprintln(os.Stderr, "gengrammar:", err)
	os.Exit(1)
}

func generate(l lockEntry, modcache, out string, update bool) (sum string, err error) {
	src, err := os.ReadFile(l.parserC(modcache))
	if err != nil {
		return "", err
	}
	sum = fmt.Sprintf("%x", sha256.Sum256(src))
	if sum != l.sum && !update {
		return "", fmt.Errorf("parser.c sha256 is %s, the lock says %q (use -update)", sum, l.sum)
	}
	g, err := parseGrammar(string(src))
	if err != nil {
		return "", err
	}
	defer func() {
		if r := recover(); r != nil {
			e, ok := r.(genError)
			if !ok {
				panic(r)
			}
			err = e
		}
	}()
	dir := filepath.Join(out, l.pkg)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	// The scanner is hand-written and not ours; wire it only if it is there.
	_, statErr := os.Stat(filepath.Join(dir, "scanner.go"))
	e := &emitter{g: g, pkg: l.pkg, hdr: fmt.Sprintf(
		"// Code generated by gengrammar from %s@%s. DO NOT EDIT.\n// Source: %s/parser.c, sha256 %s.\n\n",
		l.module, l.version, l.dir, sum)}

	// Build all three in memory first, so a failure leaves the old files.
	var tables, lex, lang bytes.Buffer
	e.tables(&tables)
	e.lex(&lex)
	e.language(&lang, statErr == nil)
	for name, b := range map[string]*bytes.Buffer{"tables.go": &tables, "lex.go": &lex, "language.go": &lang} {
		if err := os.WriteFile(filepath.Join(dir, name), b.Bytes(), 0o644); err != nil {
			return "", err
		}
	}
	if statErr != nil && e.wantsScanner {
		fmt.Fprintf(os.Stderr, "gengrammar: %s: no scanner.go yet, ExternalScanner.New is nil\n", l.pkg)
	}
	return sum, nil
}
